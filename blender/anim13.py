    """IK руки в пространстве героя: позиция кисти pos, (опц.) направление клинка zdir и «тыльной» оси ydir.
    Переменные: плечо(3), локоть, сгиб кисти (pitch), поворот кисти (yaw), крен (roll)."""
    p=AN.P_(p);a=list(p[side]);hk='h'+side;h0=list(p.get(hk,(0,0)))
    b0=(p.get('tx2',0.0),p.get('ty2',0.0),p['c'])
    v=a[:4]+[a[4]-a[0]-a[3],h0[0],h0[1]]+list(b0);seed=list(v);NB=10 if body else 7;tgt=Vector(pos);zd=Vector(zdir).normalized() if zdir else None;yd=Vector(ydir).normalized() if ydir else None
    def apply(v):
        q=dict(p);q[side]=v[:4]+[v[0]+v[3]+v[4]];q[hk]=(v[5],v[6])
        if body:q['tx2'],q['ty2'],q['c']=v[7],v[8],min(0.85,max(0.0,v[9]))
        return q
    def err(v):
        M=hand_w(apply(v),side);d=(M.translation-tgt).length;e=d*d
        if zd is not None:e+=wz*(1-M.col[2].to_3d().normalized().dot(zd))
        if yd is not None:e+=wz*0.5*(1-M.col[1].to_3d().normalized().dot(yd))
        e+=0.0006*sum((v[i]-seed[i])**2 for i in range(7))+(0.05*max(0,v[3]))**2
        if body:e+=0.02*((v[7]-seed[7])**2+(v[8]-seed[8])**2)+0.03*(v[9]-seed[9])**2
        return e
    best=err(v);st=0.35
    for it in range(iters):
        imp=False
        for i in range(NB):
            for s in(st,-st):
                w=list(v);w[i]+=s;e=err(w)
                if e<best:best,v,imp=e,w,True
        if not imp:
            st*=0.6
            if st<2e-4:break
    r=apply(v);M=hand_w(r,side);print('ikw',LBL[0],side,'pos err',round((M.translation-tgt).length,3),'dir',round(M.col[2].to_3d().normalized().dot(zd),3) if zd else '-')
    return r
